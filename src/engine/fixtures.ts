import type { Catalog, Player, Role } from "./engine";

const ROLE: Record<string, Role> = { "תופים": "drums", "בס": "bass", "פסנתר": "harmony", "גיטרה": "harmony" };
const ORDER = ["תופים", "בס", "פסנתר", "גיטרה", "טרומבון", "טנור", "אלט", "חצוצרה", "חליל", "שירה"];
export const CATALOG: Catalog = {
  role: (i) => ROLE[i] ?? "melody",
  unique: (i) => i in ROLE,
  order: (i) => (ORDER.indexOf(i) < 0 ? 99 : ORDER.indexOf(i)),
};

const mk = (rows: [string, string, string?][]): Player[] =>
  rows.map(([name, inst, backup], i) => ({ id: `p${i}-${name}`, name, instruments: [inst], backup: backup ? [backup] : [] }));

